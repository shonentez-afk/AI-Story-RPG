"""Generate an Ink draft from an engine-neutral M0 scenario."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent

def validate(data):
    scenes = {s["id"]: s for s in data["scenes"]}
    assert data["entry"] in scenes
    ids = []
    for s in data["scenes"]:
        assert s.get("ending") or s["choices"]
        for c in s["choices"]:
            assert c["next"] in scenes, c
            ids.append(c["id"])
            for kind in ("set", "inc", "when"):
                assert all(k in data["initial"] for k in c.get(kind, {})), c
    assert len(ids) == len(set(ids))
    assert len(scenes) >= 8 and len(ids) >= 10

def condition(name, value):
    if isinstance(value, dict):
        assert set(value) == {"gte"}
        return f'{name} >= {value["gte"]}'
    if isinstance(value, bool):
        return name if value else f"not {name}"
    return f"{name} == {value}"

def compile_ink(data):
    lines = ["// AUTOGENERATED from scenario.json; Ink compiler validation pending."]
    for key, value in data["initial"].items():
        lines.append(f'VAR {key} = {str(value).lower() if isinstance(value, bool) else value}')
    for scene in data["scenes"]:
        lines.extend(["", f'=== {scene["id"]} ===', scene["text"]])
        for c in scene["choices"]:
            checks = " and ".join(condition(k, v) for k, v in c.get("when", {}).items())
            lines.append(f'* {{ {checks} }} {c["text"]}' if checks else f'* {c["text"]}')
            for key, value in c.get("set", {}).items():
                lines.append(f'    ~ {key} = {str(value).lower() if isinstance(value, bool) else value}')
            for key, value in c.get("inc", {}).items():
                lines.append(f'    ~ {key} = {key} + {value}')
            lines.append(f'    -> {c["next"]}')
        if scene.get("ending"):
            lines.append("-> END")
    return "\n".join(lines) + "\n"

if __name__ == "__main__":
    src = json.loads((ROOT / "scenario.json").read_text("utf-8"))
    validate(src)
    (ROOT / "manor_mystery.ink").write_text(compile_ink(src), "utf-8")
    print(f'Validated {len(src["scenes"])} scenes, {sum(len(s["choices"]) for s in src["scenes"])} choices')
